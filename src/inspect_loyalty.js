'use strict';

/**
 * inspect_loyalty.js
 * ------------------
 * Phase 0 discovery for the LOYALTY reports. READ-ONLY: never touches Supabase
 * (load.js is not even required here), never navigates outside /mp1-reporting.
 *
 * Why this exists: the core sync (index.js) assumes every chart has a Stores
 * multi-select and Start/End date inputs, and that its output is one Mon–Sun
 * week of one store. Loyalty/customer charts break those assumptions in ways we
 * can only learn from the live hub:
 *   - some may have no Stores filter (members are estate-wide),
 *   - some may ignore the date range (a balance is a point-in-time snapshot),
 *   - all are customer-level, so they carry personal data that load.js would
 *     otherwise turn straight into TEXT columns.
 *
 * For each chart it records which filter controls exist, captures the CSV for
 * the last complete week and the week before (same store), and reports headers,
 * row counts, masked samples, store/date/customer-id columns, personal-data
 * columns, and whether the output changes with the date range. It then checks
 * Hitchin + Stevenage == both-stores for one weekly chart.
 *
 * Raw CSVs (which contain personal data) are deleted from downloads/ as soon as
 * they are parsed. A masked summary goes to debug/loyalty_inspect.json.
 *
 * Weeks are computed here from "today", deliberately ignoring START_DATE /
 * END_DATE: getWeeks() with both set returns ONE arbitrary window.
 *
 * Run:  npm run inspect:loyalty      (HEADLESS=0 to watch)
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const {
  withSession,
  reportFrame,
  SEL,
  selectChart,
  selectInterval,
  setDate,
  selectSingleStore,
  openReactSelect,
  clickOptionByText,
  clickUpdate,
  currentEmbedUrl,
  waitForResults,
  captureViaCsv,
} = require('./extract');
const { STORES, RUNTIME, fmtISO, fmtUK, addDays, mondayOf } = require('./config');

const CHARTS = [
  'Loyalty earnt and redeemed',
  'Loyalty per channel',
  'Loyalty per customer (with filters)',
  'Discounts Info (with promo code & customer info)',
  'Sales Generated by Discount Type',
  'Loyalty - Current Balance',
  'Lifetime loyalty per customer',
  'Users',
];
// Weekly chart used for the Hitchin + Stevenage == both reconciliation.
const RECON_CHART = process.env.RECON_CHART || 'Loyalty earnt and redeemed';

// Candidate personal-data headers (Phase 1 will turn this into dropColumns).
const PII_RULES = [
  { why: 'name', rx: /^(first|last|full|sur|given|customer|user|member|account)[ _-]?name$|^name$/i },
  { why: 'email', rx: /e-?mail/i },
  { why: 'phone', rx: /phone|mobile|tel(ephone)?\b/i },
  { why: 'address', rx: /address|street|post ?code|zip|city|town|county/i },
  { why: 'birthday', rx: /birth|\bdob\b/i },
  { why: 'marketing', rx: /marketing|consent|opt[ _-]?in/i },
  { why: 'card/token', rx: /card|token|\bpan\b|last ?4|fingerprint/i },
];
const UUID_RX = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const EMAIL_RX = /[^\s@]+@[^\s@]+\.[^\s@]+/;
const PHONE_RX = /^\+?[\d\s()-]{9,}$/;

function piiReason(header) {
  const hit = PII_RULES.find((r) => r.rx.test(header));
  return hit ? hit.why : null;
}

function lastCompleteWeeks(n) {
  const now = new Date();
  const today = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate()));
  const lastMonday = addDays(mondayOf(today), -7);
  const out = [];
  for (let i = 0; i < n; i++) {
    const s = addDays(lastMonday, -7 * i);
    const e = addDays(s, 6);
    out.push({ startISO: fmtISO(s), endISO: fmtISO(e), startUK: fmtUK(s), endUK: fmtUK(e) });
  }
  return out; // newest first
}

async function detectFilters(frame) {
  const count = (sel) => frame.locator(sel).count().catch(() => 0);
  const dataTests = await frame
    .locator('[data-test^="null-"]')
    .evaluateAll((els) => els.map((e) => e.getAttribute('data-test')))
    .catch(() => []);
  const dateInputs = await frame
    .locator('input[id^="rdp-form-control-"]')
    .evaluateAll((els) => els.map((e) => e.id))
    .catch(() => []);
  return {
    stores: (await count(SEL.stores)) > 0,
    startDate: (await count(SEL.startDate)) > 0,
    endDate: (await count(SEL.endDate)) > 0,
    interval: (await count(SEL.interval)) > 0,
    channels: (await count(SEL.channels)) > 0,
    controls: [...new Set(dataTests)],
    dateInputs,
  };
}

/** Select several stores (for the both-stores reconciliation run). */
async function selectStores(page, frame, storeNames) {
  await openReactSelect(frame, SEL.stores);
  await page.waitForTimeout(400);
  for (const label of ['Deselect all', 'Deselect All', 'Clear all']) {
    const link = frame.getByText(label, { exact: true }).first();
    if (await link.count().catch(() => 0)) {
      await link.click().catch(() => {});
      break;
    }
  }
  await page.waitForTimeout(250);
  for (const s of storeNames) {
    const menuOpen = await frame.locator(SEL.option).first().isVisible().catch(() => false);
    if (!menuOpen) await openReactSelect(frame, SEL.stores);
    await clickOptionByText(page, frame, s, { timeout: 8000 });
    await page.waitForTimeout(250);
  }
  await frame.locator('body').press('Escape').catch(() => {});
  const vals = await frame
    .locator(`${SEL.stores} input[name="stores"]`)
    .evaluateAll((els) => els.map((e) => e.value))
    .catch(() => []);
  console.log(`[inspect-loyalty] Stores selected: ${JSON.stringify(vals)}`);
  return vals;
}

/**
 * Apply whatever filters this chart has, run it, capture the CSV, delete the raw
 * file (personal data) and return { columns, rows, storesShown }.
 * stores: null = leave the Stores filter alone; array = select exactly those.
 */
async function runChart(page, { chart, week, stores, filters, tag }) {
  const frame = reportFrame(page);
  await selectChart(page, frame, chart);
  await page.waitForTimeout(1500);
  if (filters.interval) await selectInterval(page, frame);
  await setWindow(page, frame, week, filters);
  let storesShown = null;
  if (filters.stores && stores) {
    if (stores.length === 1) await selectSingleStore(page, frame, stores[0]);
    else await selectStores(page, frame, stores);
    storesShown = await frame
      .locator(`${SEL.stores} input[name="stores"]`)
      .evaluateAll((els) => els.map((e) => e.value))
      .catch(() => []);
  } else if (!filters.stores) {
    console.log('[inspect-loyalty] No Stores control — skipping.');
  }

  const prevUrl = currentEmbedUrl(page);
  await clickUpdate(page, frame);
  await waitForResults(page, prevUrl);
  const captured = await captureViaCsv(page, `inspect_loyalty_${tag}`);
  if (!captured) throw new Error(`No CSV captured for "${chart}" (${tag}).`);
  try {
    fs.unlinkSync(path.join(RUNTIME.downloadsDir, captured.sourceFile));
  } catch {
    /* already gone */
  }
  return { columns: captured.columns, rows: captured.rows, storesShown };
}

/**
 * Moving the window FORWARD breaks core setDate(): typing a start date that is
 * after the current end date leaves the start calendar open over the end input
 * and the end click times out (seen going 28/09..04/10 -> 05/10..11/10). So when
 * the new start is after the current end, set the end first. Core setDate() is
 * left untouched; this ordering only applies to the loyalty path.
 */
function ukToNum(s) {
  const m = /^(\d{2})\/(\d{2})\/(\d{4})$/.exec(String(s || '').trim());
  return m ? Number(m[3] + m[2] + m[1]) : NaN;
}

async function setWindow(page, frame, week, filters) {
  const curEnd = filters.endDate ? await frame.locator(SEL.endDate).inputValue().catch(() => '') : '';
  const order = ukToNum(week.startUK) > ukToNum(curEnd) ? ['end', 'start'] : ['start', 'end'];
  for (const which of order) {
    const has = which === 'start' ? filters.startDate : filters.endDate;
    if (!has) {
      console.log(`[inspect-loyalty] No ${which}-date control — skipping.`);
      continue;
    }
    await safeSetDate(page, frame, which, which === 'start' ? week.startUK : week.endUK);
  }
}

async function safeSetDate(page, frame, which, ddmmyyyy) {
  await setDate(page, frame, which, ddmmyyyy);
  const got = await frame.locator(which === 'start' ? SEL.startDate : SEL.endDate).inputValue().catch(() => '');
  if (got !== ddmmyyyy) throw new Error(`${which} date shows "${got}", wanted ${ddmmyyyy}`);
}

function signature(rows) {
  const lines = rows.map((r) => JSON.stringify(r)).sort();
  return crypto.createHash('sha1').update(lines.join('\n')).digest('hex').slice(0, 12);
}

function maskRow(row, columns) {
  const o = {};
  for (const c of columns) {
    const v = row[c] == null ? '' : String(row[c]);
    if (piiReason(c) || EMAIL_RX.test(v) || PHONE_RX.test(v.trim())) o[c] = v ? '«masked»' : '';
    else if (UUID_RX.test(v.trim())) o[c] = v.trim().slice(0, 8) + '…';
    else o[c] = v.length > 40 ? v.slice(0, 40) + '…' : v;
  }
  return o;
}

function analyse(columns, rows) {
  const storeCols = columns.filter((c) => /store|site|location|restaurant|venue/i.test(c));
  const dateCols = columns.filter((c) => /date|week|day|month|time|created|_at$|\bat\b|period/i.test(c));
  const uuidCols = columns.filter((c) => {
    const vals = rows.map((r) => String(r[c] || '').trim()).filter(Boolean);
    return vals.length > 0 && vals.filter((v) => UUID_RX.test(v)).length / vals.length > 0.9;
  });
  const idNamed = columns.filter((c) => /(customer|user|member|account)[ _-]?(id|uuid)|^uuid$|^id$/i.test(c));
  const pii = columns.map((c) => ({ c, why: piiReason(c) })).filter((x) => x.why);
  // Columns not matched by a header rule but whose VALUES look like email/phone.
  const piiByValue = columns.filter(
    (c) =>
      !piiReason(c) &&
      rows.some((r) => {
        const v = String(r[c] || '').trim();
        return EMAIL_RX.test(v) || (PHONE_RX.test(v) && !/^[\d.,-]+$/.test(v));
      })
  );
  const genericNames = columns.filter((c) => /name/i.test(c) && !piiReason(c));
  const storeValues = {};
  for (const c of storeCols) storeValues[c] = [...new Set(rows.map((r) => r[c]))].slice(0, 10);
  return { storeCols, storeValues, dateCols, uuidCols, idNamed, pii, piiByValue, genericNames };
}

function numericSums(columns, rows) {
  const clean = rows.filter((r) => !Object.values(r).some((v) => String(v).startsWith('~')));
  const sums = {};
  for (const c of columns) {
    const vals = clean.map((r) => String(r[c] ?? '').trim()).filter(Boolean);
    if (!vals.length) continue;
    const nums = vals.map((v) => v.replace(/[£$,%\s]/g, ''));
    if (!nums.every((v) => /^-?\d*\.?\d+$/.test(v))) continue;
    sums[c] = nums.reduce((a, v) => a + Number(v), 0);
  }
  return { rows: clean.length, sums };
}

async function main() {
  fs.mkdirSync(RUNTIME.debugDir, { recursive: true });
  const [weekA, weekB] = lastCompleteWeeks(2);
  const store = STORES[0];
  console.log('==========================================================');
  console.log(' Loyalty Phase 0 discovery (read-only, no Supabase writes)');
  console.log(`  Week A : ${weekA.startISO}..${weekA.endISO}  (last complete)`);
  console.log(`  Week B : ${weekB.startISO}..${weekB.endISO}`);
  console.log(`  Store  : ${store}`);
  console.log('==========================================================\n');

  const results = [];
  let recon = null;

  await withSession(async (page) => {
    const frame = reportFrame(page);

    for (const chart of CHARTS) {
      const res = { chart };
      results.push(res);
      console.log(`\n---------------- ${chart} ----------------`);
      try {
        await selectChart(page, frame, chart);
        await page.waitForTimeout(2000);
        const filters = await detectFilters(frame);
        res.filters = filters;
        console.log(`[inspect-loyalty] filters: ${JSON.stringify(filters)}`);

        const a = await runChart(page, { chart, week: weekA, stores: [store], filters, tag: 'A' });
        res.columns = a.columns;
        res.rowsA = a.rows.length;
        res.storesShown = a.storesShown;
        res.analysis = analyse(a.columns, a.rows);
        res.samples = a.rows.slice(0, 3).map((r) => maskRow(r, a.columns));
        res.sigA = signature(a.rows);

        if (filters.startDate || filters.endDate) {
          const b = await runChart(page, { chart, week: weekB, stores: [store], filters, tag: 'B' });
          res.rowsB = b.rows.length;
          res.sigB = signature(b.rows);
          res.changesWithDate = res.sigA !== res.sigB;
        } else {
          res.changesWithDate = false;
        }

        console.log(`[inspect-loyalty] headers (${a.columns.length}): ${JSON.stringify(a.columns)}`);
        console.log(`[inspect-loyalty] rows A=${res.rowsA} B=${res.rowsB ?? '-'} changesWithDate=${res.changesWithDate}`);
        console.log(`[inspect-loyalty] analysis: ${JSON.stringify(res.analysis)}`);
        console.log('[inspect-loyalty] masked samples:');
        for (const s of res.samples) console.log('   ' + JSON.stringify(s));
      } catch (e) {
        res.error = e.message;
        console.error(`[inspect-loyalty] FAILED ${chart}: ${e.message}`);
      }
    }

    // ---- Hitchin + Stevenage == both -------------------------------------
    const rc = results.find((r) => r.chart === RECON_CHART);
    if (rc && rc.filters && rc.filters.stores && STORES.length >= 2) {
      console.log(`\n---------------- Reconciliation: ${RECON_CHART} ----------------`);
      try {
        const per = {};
        for (const s of STORES) {
          const r = await runChart(page, { chart: RECON_CHART, week: weekA, stores: [s], filters: rc.filters, tag: `R_${s}` });
          per[s] = numericSums(r.columns, r.rows);
        }
        const both = await runChart(page, { chart: RECON_CHART, week: weekA, stores: STORES, filters: rc.filters, tag: 'R_both' });
        const all = numericSums(both.columns, both.rows);
        const cols = Object.keys(all.sums);
        const lines = cols.map((c) => {
          const parts = STORES.map((s) => per[s].sums[c] || 0);
          const sum = parts.reduce((x, y) => x + y, 0);
          return { column: c, perStore: parts, sumOfStores: +sum.toFixed(2), both: +all.sums[c].toFixed(2), diff: +(all.sums[c] - sum).toFixed(2) };
        });
        recon = {
          chart: RECON_CHART,
          week: weekA.startISO,
          rows: { ...Object.fromEntries(STORES.map((s) => [s, per[s].rows])), both: all.rows },
          storesShownBoth: both.storesShown,
          columns: lines,
        };
        console.log(JSON.stringify(recon, null, 2));
      } catch (e) {
        recon = { chart: RECON_CHART, error: e.message };
        console.error(`[inspect-loyalty] reconciliation FAILED: ${e.message}`);
      }
    } else {
      recon = { chart: RECON_CHART, error: 'chart has no Stores filter or failed above — not reconciled' };
    }
  });

  // ---- Summary table ------------------------------------------------------
  console.log('\n========================= PHASE 0 SUMMARY =========================');
  console.log('chart | store filter | date filter | weekly/snapshot | rows A/B | customer id col | personal-data cols');
  for (const r of results) {
    if (r.error) {
      console.log(`${r.chart} | ERROR: ${r.error}`);
      continue;
    }
    const f = r.filters;
    const kind = r.changesWithDate ? 'weekly' : 'snapshot';
    const ids = [...new Set([...r.analysis.idNamed, ...r.analysis.uuidCols])].join(', ') || 'NONE';
    const pii = [...r.analysis.pii.map((p) => `${p.c} (${p.why})`), ...r.analysis.piiByValue.map((c) => `${c} (value)`)].join(', ') || '-';
    console.log(
      `${r.chart} | ${f.stores ? 'yes' : 'no'} | ${f.startDate && f.endDate ? 'yes' : f.startDate || f.endDate ? 'partial' : 'no'} | ${kind} | ${r.rowsA}/${r.rowsB ?? '-'} | ${ids} | ${pii}`
    );
  }
  console.log('===================================================================');

  const outFile = path.join(RUNTIME.debugDir, 'loyalty_inspect.json');
  fs.writeFileSync(outFile, JSON.stringify({ weekA, weekB, store, results, recon }, null, 2), 'utf8');
  console.log(`\n[inspect-loyalty] Masked summary -> ${outFile}`);
}

// Exported so follow-up probes can reuse the same filter/capture path.
module.exports = { CHARTS, detectFilters, runChart, analyse, numericSums, signature, maskRow, lastCompleteWeeks };

if (require.main === module) {
  main().catch((err) => {
    console.error('[inspect-loyalty] Failed:', err.message);
    process.exit(1);
  });
}
